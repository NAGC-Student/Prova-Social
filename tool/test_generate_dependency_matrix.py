import hashlib
import tempfile
import unittest
from pathlib import Path

import generate_dependency_matrix as matrix

ROOT = Path(__file__).resolve().parents[1]

MINIMAL_LOCK = """# Generated by pub
packages:
  crypto:
    dependency: "direct main"
    description:
      name: crypto
      sha256: "aa"
      url: "https://pub.dev"
    source: hosted
    version: "3.0.7"
  flutter:
    dependency: "direct main"
    description: flutter
    source: sdk
    version: "0.0.0"
  paddleocr_android:
    dependency: "direct main"
    description:
      path: "packages/paddleocr_android"
      relative: true
    source: path
    version: "0.1.0"
  flutter_test:
    dependency: "direct dev"
    description: flutter
    source: sdk
    version: "0.0.0"
  typed_data:
    dependency: transitive
    description:
      name: typed_data
      sha256: "bb"
      url: "https://pub.dev"
    source: hosted
    version: "1.4.0"
sdks:
  dart: ">=3.13.0 <4.0.0"
  flutter: ">=3.47.0"
"""


class ParseLockTest(unittest.TestCase):
    def test_le_origem_hosted_path_e_sdk(self):
        packages, sdks = matrix.parse_lock(MINIMAL_LOCK)
        by_name = {package["name"]: package for package in packages}
        self.assertEqual(len(packages), 5)
        self.assertEqual(by_name["crypto"]["origin"], "hosted")
        self.assertEqual(by_name["crypto"]["dependency"], "direct main")
        self.assertEqual(by_name["crypto"]["version"], "3.0.7")
        self.assertEqual(
            by_name["paddleocr_android"]["origin"],
            "path: packages/paddleocr_android",
        )
        self.assertEqual(by_name["flutter"]["origin"], "sdk: flutter")
        self.assertEqual(by_name["flutter_test"]["dependency"], "direct dev")
        self.assertEqual(by_name["typed_data"]["dependency"], "transitive")
        self.assertEqual(sdks["dart"], ">=3.13.0 <4.0.0")
        self.assertEqual(sdks["flutter"], ">=3.47.0")

    def test_recusa_pacote_sem_versao(self):
        broken = MINIMAL_LOCK.replace('    version: "3.0.7"\n', "")
        with self.assertRaises(matrix.LockError):
            matrix.parse_lock(broken)

    def test_recusa_estrutura_desconhecida(self):
        broken = MINIMAL_LOCK.replace("packages:\n", "packages:\n  solto: solto\n")
        with self.assertRaises(matrix.LockError):
            matrix.parse_lock(broken)

    def test_recusa_secao_ausente(self):
        with self.assertRaises(matrix.LockError):
            matrix.parse_lock("sdks:\n  dart: \">=3.13.0 <4.0.0\"\n")

    def test_recusa_pacote_repetido(self):
        duplicated = MINIMAL_LOCK.replace(
            "  typed_data:\n",
            "  crypto:\n    dependency: transitive\n    source: hosted\n"
            '    version: "3.0.7"\n  typed_data:\n',
        )
        with self.assertRaises(matrix.LockError):
            matrix.parse_lock(duplicated)

    def test_lock_real_do_repositorio(self):
        packages, sdks = matrix.parse_lock(
            (ROOT / "pubspec.lock").read_text(encoding="utf-8")
        )
        self.assertTrue(packages)
        self.assertIn("dart", sdks)
        self.assertTrue(
            all(package["version"] for package in packages),
            "todo pacote resolvido precisa de versão",
        )


class RenderTest(unittest.TestCase):
    def setUp(self):
        self.lock_bytes = MINIMAL_LOCK.encode("utf-8")
        self.sha = hashlib.sha256(self.lock_bytes).hexdigest()

    def test_matriz_traz_sha_data_e_versoes(self):
        text = matrix.render(self.lock_bytes, None, "2026-11-08")
        self.assertIn(f"sha: {self.sha}", text)
        self.assertIn("atualizado: 2026-11-08", text)
        self.assertIn("| `crypto` | `3.0.7` | hosted |", text)
        self.assertIn("| `typed_data` | `1.4.0` | hosted |", text)
        self.assertIn("| `dart` | `>=3.13.0 <4.0.0` |", text)
        self.assertIn("5 — 3 diretos de app", text)

    def test_data_e_preservada_enquanto_o_lock_nao_muda(self):
        first = matrix.render(self.lock_bytes, None, "2026-11-08")
        later = matrix.render(self.lock_bytes, first, "2026-12-25")
        self.assertEqual(first, later)

    def test_lock_novo_recebe_data_nova(self):
        first = matrix.render(self.lock_bytes, None, "2026-11-08")
        bumped = self.lock_bytes.replace(b'"3.0.7"', b'"3.0.8"')
        later = matrix.render(bumped, first, "2026-12-25")
        self.assertIn("atualizado: 2026-12-25", later)
        self.assertIn("| `crypto` | `3.0.8` | hosted |", later)
        self.assertNotIn(hashlib.sha256(bumped).hexdigest(), first)


class CheckModeTest(unittest.TestCase):
    def setUp(self):
        self.temporary_directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary_directory.cleanup)
        self.directory = Path(self.temporary_directory.name)
        self.lock = self.directory / "pubspec.lock"
        self.output = self.directory / "Matriz de dependências.md"
        self.lock.write_text(MINIMAL_LOCK, encoding="utf-8")

    def run_main(self, *extra):
        return matrix.main(
            ["--lock", str(self.lock), "--output", str(self.output), *extra]
        )

    def test_gera_e_confere(self):
        self.assertEqual(self.run_main(), 0)
        self.assertTrue(self.output.exists())
        self.assertEqual(self.run_main("--check"), 0)

    def test_check_falha_sem_matriz(self):
        self.assertEqual(self.run_main("--check"), 1)

    def test_check_falha_quando_o_lock_muda(self):
        self.assertEqual(self.run_main(), 0)
        self.lock.write_text(
            MINIMAL_LOCK.replace('"1.4.0"', '"1.4.1"'), encoding="utf-8"
        )
        self.assertEqual(self.run_main("--check"), 1)
        self.assertEqual(self.run_main(), 0)
        self.assertEqual(self.run_main("--check"), 0)

    def test_check_falha_quando_a_matriz_foi_editada_a_mao(self):
        self.assertEqual(self.run_main(), 0)
        self.output.write_text(
            self.output.read_text(encoding="utf-8").replace("`3.0.7`", "`9.9.9`"),
            encoding="utf-8",
        )
        self.assertEqual(self.run_main("--check"), 1)

    def test_check_falha_com_lock_ilegivel(self):
        self.assertEqual(self.run_main(), 0)
        self.lock.write_text("packages:\n  crypto:\n", encoding="utf-8")
        self.assertEqual(self.run_main("--check"), 1)

    def test_lock_ausente_falha_sem_traceback(self):
        self.lock.unlink()
        self.assertEqual(self.run_main(), 1)


if __name__ == "__main__":
    unittest.main()